/**
 * Menghitung koordinat poligon batas konsesi perkebunan kelapa sawit
 * secara proporsional dengan luas areal dalam hektar (1 Ha = 0.01 km²)
 */
export function generateConcessionPolygon(
  centerLat: number,
  centerLon: number,
  areaHectares: number,
  seed: number = 1
): [number, number][] {
  // Radius ekuivalen dalam km
  const radiusKm = Math.sqrt((areaHectares * 0.01) / Math.PI);
  // Konversi km ke derajat (~111 km per derajat latitude)
  const radiusDeg = radiusKm / 111;

  // 10 titik batas blok konsesi perkebunan
  const numPoints = 10;
  const coordinates: [number, number][] = [];

  for (let i = 0; i < numPoints; i++) {
    const angle = (i * 2 * Math.PI) / numPoints;
    // Variasi bentuk blok konsesi sawit (afdeling perkebunan)
    const factor = 0.85 + 0.28 * Math.abs(Math.sin(2 * angle + seed)) + 0.12 * Math.cos(4 * angle + seed * 0.5);
    const r = radiusDeg * factor;

    const latOffset = r * Math.cos(angle);
    const lonOffset = (r * Math.sin(angle)) / Math.cos((centerLat * Math.PI) / 180);

    coordinates.push([
      Math.round((centerLat + latOffset) * 10000) / 10000,
      Math.round((centerLon + lonOffset) * 10000) / 10000,
    ]);
  }

  // Tutup poligon dengan titik awal
  coordinates.push(coordinates[0]);
  return coordinates;
}

